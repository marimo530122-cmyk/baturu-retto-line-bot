"""LLMへ渡すプロンプトテンプレート集。"""
from app.custom_instructions import CUSTOM_CLINICAL_INSTRUCTIONS


def _with_custom_instructions(base_prompt: str) -> str:
    """現場からのフィードバック(app/custom_instructions.py)が設定されていれば、
    プロンプトの末尾に追記する。空ならそのまま返す。"""
    if not CUSTOM_CLINICAL_INSTRUCTIONS:
        return base_prompt
    return f"{base_prompt}\n\n【現場からの追加ルール】\n{CUSTOM_CLINICAL_INSTRUCTIONS}"


